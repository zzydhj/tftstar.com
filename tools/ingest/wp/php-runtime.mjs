/**
 * Locates the local PHP and produces the php.ini it needs.
 *
 *   node tools/ingest/wp/php-runtime.mjs          write work/php.ini, report
 *
 * Two facts about how winget installs PHP make this necessary rather than
 * optional. The package is compiled expecting `extension_dir=C:\php\ext`, so on a
 * winget install it points at a directory that does not exist; and no php.ini is
 * loaded at all, which means mysqli is absent and WordPress dies on its first
 * database call with an "undefined function mysqli_connect" rather than a message
 * about configuration.
 *
 * The install path carries a package-source hash, so it is discovered here at
 * runtime instead of being written down once and breaking on the next upgrade.
 */
import { execFileSync } from 'node:child_process';
import { readdirSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { exists, readFile, writeFile } from '../../lib/fs-utils.js';
import { root } from '../../lib/paths.js';

/** WordPress core plus Woodmart, WooCommerce, Elementor and Translate Press. */
const REQUIRED = ['mysqli', 'curl', 'gd', 'intl', 'mbstring', 'zip', 'openssl', 'fileinfo', 'exif', 'pdo_mysql'];

const INI = join(root, 'work', 'php.ini');

/** @returns the absolute path to php.exe, or null when it cannot be found. */
export function findPhp() {
  if (process.env.PHP_EXE && exists(process.env.PHP_EXE)) return process.env.PHP_EXE;

  const located = wherePhp();
  if (located) return located;

  const packages = join(process.env.LOCALAPPDATA ?? '', 'Microsoft', 'WinGet', 'Packages');
  if (!exists(packages)) return null;

  // Directory names look like PHP.PHP.8.3_Microsoft.Winget.Source_8wekyb3d8bbwe, so
  // the prefix is matched rather than the whole name: the path must keep resolving
  // after an upgrade changes the version inside it.
  const candidates = readdirSync(packages)
    .filter((name) => name.startsWith('PHP.PHP.'))
    .map((name) => join(packages, name, 'php.exe'))
    .filter((candidate) => exists(candidate))
    .sort();

  return candidates.at(-1) ?? null;
}

function wherePhp() {
  try {
    // stderr is discarded deliberately: where.exe prints "could not find" in the
    // console codepage, which arrives here as mojibake on a normal first run when
    // PATH has not been refreshed after the install.
    const found = execFileSync('where.exe', ['php'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] })
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line.toLowerCase().endsWith('php.exe'));
    return found[0] ?? null;
  } catch {
    return null;
  }
}

/**
 * The ini, written with absolute paths.
 *
 * Quotes matter: the value is a Windows path with backslashes, and an unquoted
 * value would be read up to the first space in "Program Files" style segments.
 */
export function writeIni(phpExe) {
  const home = dirname(phpExe);
  const extensionDir = join(home, 'ext');

  const lines = [
    '; Generated by tools/ingest/wp/php-runtime.mjs. Edit that script, not this file.',
    `extension_dir = "${extensionDir}"`,
    '; The live site died of "Allowed memory size of 134217728 bytes exhausted", and',
    '; importing a 40 MB dump into Woodmart renders far more than that per request.',
    'memory_limit = 1024M',
    'max_execution_time = 0',
    'display_errors = Off',
    'log_errors = On',
    `error_log = "${join(root, 'work', 'php-error.log')}"`,
    'upload_max_filesize = 256M',
    'post_max_size = 256M',
    '',
    '[extensions]',
    ...REQUIRED.map((name) => `extension = ${name}`),
    '',
  ];

  writeFile(INI, lines.join('\n'));
  return { ini: INI, extensionDir, home };
}

/** Runs `php -m` under the given ini and returns the module list it reports. */
export function loadedExtensions(phpExe, ini) {
  const out = execFileSync(phpExe, ['-c', ini, '-m'], { encoding: 'utf8' });
  return out
    .split(/\r?\n/)
    .map((line) => line.trim().toLowerCase())
    .filter((line) => line !== '' && !line.startsWith('['));
}

export function verify(phpExe, ini) {
  const loaded = new Set(loadedExtensions(phpExe, ini));
  const missing = REQUIRED.filter((name) => !loaded.has(name.toLowerCase()));
  return { loaded, missing };
}

/* CLI ---------------------------------------------------------------------- */

if (process.argv[1] && basename(process.argv[1]).startsWith('php-runtime')) {
  const phpExe = findPhp();

  if (!phpExe) {
    console.error('\n  php.exe not found. Install it, or point me at it:\n');
    console.error('    winget install -e --id PHP.PHP.8.3');
    console.error('    set PHP_EXE=C:\\path\\to\\php.exe\n');
    process.exit(1);
  }

  const { ini, extensionDir } = writeIni(phpExe);
  const version = execFileSync(phpExe, ['-r', 'echo PHP_VERSION;'], { encoding: 'utf8' });
  const { missing } = verify(phpExe, ini);

  console.log(`\n  php      ${version} - ${phpExe}`);
  console.log(`  ext dir  ${extensionDir}`);
  console.log(`  ini      ${ini}`);

  if (missing.length > 0) {
    console.error(`\n  FAILED to load: ${missing.join(', ')}`);
    console.error('  WordPress cannot run without these; see work/php-error.log for the loader message.\n');
    console.error(readFile(ini));
    process.exit(1);
  }

  console.log(`  modules  ${REQUIRED.join(', ')} - all loaded\n`);
}
